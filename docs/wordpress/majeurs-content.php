/** Tags collected during this request, sent once at shutdown */
function majeurs_content_queue_tags( array $tags ) {
	global $majeurs_revalidate_tags;
	if ( ! is_array( $majeurs_revalidate_tags ) ) {
		$majeurs_revalidate_tags = array();
		add_action( 'shutdown', 'majeurs_content_send_tags' );
	}
	$majeurs_revalidate_tags = array_merge( $majeurs_revalidate_tags, $tags );
}

function majeurs_content_send_tags() {
	global $majeurs_revalidate_tags;
	$url    = defined( 'MAJEURS_REVALIDATE_URL' ) ? MAJEURS_REVALIDATE_URL : get_option( 'majeurs_revalidate_url' );
	$secret = defined( 'MAJEURS_REVALIDATE_SECRET' ) ? MAJEURS_REVALIDATE_SECRET : get_option( 'majeurs_revalidate_secret' );
	if ( ! $url || ! $secret || empty( $majeurs_revalidate_tags ) ) {
		return;
	}
	wp_remote_post( untrailingslashit( $url ) . '/api/revalidate/', array(
		'timeout'  => 5,
		'blocking' => false,
		'headers'  => array( 'Content-Type' => 'application/json' ),
		'body'     => wp_json_encode( array( 'secret' => $secret, 'tags' => array_values( array_unique( $majeurs_revalidate_tags ) ) ) ),
	) );
}

/** The cache tags Next.js stores a post's data under (lib/api/*, lib/content/get.ts, lib/seo.ts) */
function majeurs_content_post_tags( $post ) {
	$slug = $post->post_name;
	$path = wp_make_link_relative( get_permalink( $post ) );
	$seo  = array( 'seo:' . $path );
	switch ( $post->post_type ) {
		case 'page':
			return array_merge( array( 'page:' . ( $slug ? $slug : 'home' ) ), $seo );
		case 'post':
			return array_merge( array( 'post:' . $slug, 'post-list' ), $seo );
		case 'product':
			return array_merge( array( 'product:' . $slug, 'product-list' ), $seo );
		case 'product_variation':
			$parent = get_post( $post->post_parent );
			return $parent ? majeurs_content_post_tags( $parent ) : array();
		case 'project':
			return array_merge( array( 'project:' . $slug, 'project-list' ), $seo );
		case 'career':
			return array_merge( array( 'career:' . $slug, 'careers' ), $seo );
	}
	return array();
}

add_action( 'save_post', function ( $post_id, $post ) {
	if ( wp_is_post_revision( $post_id ) || wp_is_post_autosave( $post_id ) || in_array( $post->post_status, array( 'auto-draft', 'inherit' ), true ) ) {
		return;
	}
	majeurs_content_queue_tags( majeurs_content_post_tags( $post ) );
}, 99, 2 );

