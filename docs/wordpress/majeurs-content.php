/**
 * Majeurs headless: editable page copy (Secure Custom Fields / ACF) and cache refresh on save
 *
 * Install: needs Secure Custom Fields (free, from WordPress.org) or ACF Pro; the lists are repeater fields, which
 * free ACF lacks. WP admin > Snippets > Add New > paste this file (without the opening <?php tag),
 * "Run snippet everywhere", Activate.
 *
 * 1. Field groups. Each page the Next.js site renders from WordPress gets a "… content" box in wp-admin > Pages > edit,
 *    holding the copy and images shown on majeurs.com (the Elementor layout of that page is no longer used).
 *    Copy shared by many pages (the "Customize your furniture style" and "Shop Now" bands, the "Need help?" strip)
 *    and the /project/ archive, which has no page, are on wp-admin > Site content.
 *    Generated from lib/content/pages/*.ts and lib/content/site.ts by `npm run content:acf`: change those files,
 *    not the JSON below.
 *    Read by Next.js from GET /wp-json/wp/v2/pages/<id>?_fields=acf&acf_format=standard
 *    and GET /wp-json/majeurs/v1/content/site  -> { "<section>": { "<field>": value, … }, … }
 *
 * 2. Import. POST /wp-json/majeurs/v1/content/seed  { "page": 70 | "site": "shopNowBand", "values": { … }, "overwrite": false }
 *    (needs edit_pages, e.g. an admin's Application Password) writes the site's current copy into every field of that
 *    page or Site content section that was never saved (all of them with overwrite). Image URLs under
 *    wp-content/uploads become their media library item.  -> { "updated": [], "skipped": [], "missing_images": [] }
 *    `npm run content:seed` sends every page.
 *
 * 3. Cache refresh. Saving a page, post, product, project, job or Site content, or editing a product or blog category or tag, POSTs
 *    { "secret", "tags" } to <Next.js site>/api/revalidate/ once the request ends, so the change shows on the next page
 *    load instead of within the hour. Settings > General > "Majeurs site URL" and "Majeurs revalidate secret"
 *    (= REVALIDATE_SECRET in Next.js), or define MAJEURS_REVALIDATE_URL / MAJEURS_REVALIDATE_SECRET in wp-config.php.
 */

/* ---------- 1. Field groups ---------- */

add_action( 'acf/include_fields', 'majeurs_content_register_groups' );

function majeurs_content_register_groups() {
	if ( ! function_exists( 'acf_add_local_field_group' ) ) {
		return;
	}
	foreach ( majeurs_content_field_groups() as $group ) {
		acf_add_local_field_group( $group );
	}
}

add_action( 'acf/init', function () {
	if ( function_exists( 'acf_add_options_page' ) ) {
		acf_add_options_page( array(
			'page_title' => 'Site content',
			'menu_title' => 'Site content',
			'menu_slug'  => 'majeurs-site-content',
			'capability' => 'edit_pages',
			'icon_url'   => 'dashicons-edit-page',
			'position'   => 21,
			'redirect'   => false,
		) );
	}
} );

