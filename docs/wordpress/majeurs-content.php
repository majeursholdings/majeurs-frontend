/** Every Site content section's values, formatted like acf_format=standard, under the definition's field names */
function majeurs_content_site() {
	$out = array();
	if ( function_exists( 'get_field' ) ) {
		foreach ( majeurs_content_field_groups() as $group ) {
			if ( empty( $group['majeurs_section'] ) ) {
				continue;
			}
			$section = $group['majeurs_section'];
			$values  = array();
			foreach ( $group['fields'] as $field ) {
				$values[ substr( $field['name'], strlen( $section ) + 1 ) ] = majeurs_content_option_saved( $field['name'] ) ? get_field( $field['name'], 'option' ) : null;
			}
			$out[ $section ] = $values;
		}
	}
	$response = rest_ensure_response( (object) $out );
	$response->header( 'Cache-Control', 'no-store' );
	return $response;
}

/** ACF keeps Site content in wp_options as options_<name>; absent means never saved */
function majeurs_content_option_saved( $name ) {
	return null !== get_option( 'options_' . $name, null );
}

function majeurs_content_seed( WP_REST_Request $request ) {
	if ( ! function_exists( 'update_field' ) ) {
		return new WP_Error( 'majeurs_no_acf', 'Secure Custom Fields / ACF is not active.', array( 'status' => 500 ) );
	}
	$page  = (int) $request['page'];
	$site  = (string) $request['site'];
	$group = null;
	foreach ( majeurs_content_field_groups() as $candidate ) {
		$match = $site ? ( $candidate['majeurs_section'] ?? '' ) === $site : ( empty( $candidate['majeurs_section'] ) && (int) $candidate['location'][0][0]['value'] === $page );
		if ( $match ) {
			$group = $candidate;
		}
	}
	if ( ! $group || ( ! $site && 'page' !== get_post_type( $page ) ) ) {
		return new WP_Error( 'majeurs_no_fields', 'No content fields for this page or section.', array( 'status' => 404 ) );
	}
	$target = $site ? 'option' : $page;

	$values    = (array) $request['values'];
	$overwrite = (bool) $request['overwrite'];
	$missing   = array();
	$report    = array( 'updated' => array(), 'skipped' => array() );
	foreach ( $group['fields'] as $field ) {
		// Site content fields are stored as <section>_<field>; the values use the definition's names
		$name = $site ? substr( $field['name'], strlen( $site ) + 1 ) : $field['name'];
		if ( ! array_key_exists( $name, $values ) ) {
			continue;
		}
		// saved at least once, even if an editor left it empty
		$saved = $site ? majeurs_content_option_saved( $field['name'] ) : metadata_exists( 'post', $page, $name );
		if ( ! $overwrite && $saved ) {
			$report['skipped'][] = $name;
			continue;
		}
		update_field( $field['key'], majeurs_content_to_acf( $field, $values[ $name ], $missing ), $target );
		$report['updated'][] = $name;
	}
	if ( $site ) {
		majeurs_content_queue_tags( array( 'site-content' ) );
	}
	$report['missing_images'] = array_values( array_unique( $missing ) );
	return rest_ensure_response( $report );
}

/** A value from lib/content (URL, { label, href, external }, rows) -> what update_field() stores */
function majeurs_content_to_acf( $field, $value, &$missing ) {
	switch ( $field['type'] ) {
		case 'image':
			$id = majeurs_content_attachment_id( (string) $value );
			if ( ! $id && $value ) {
				$missing[] = (string) $value;
			}
			return $id ? $id : '';
		case 'link':
			if ( ! is_array( $value ) || empty( $value['href'] ) ) {
				return '';
			}
			return array(
				'title'  => (string) ( $value['label'] ?? '' ),
				'url'    => (string) $value['href'],
				'target' => empty( $value['external'] ) ? '' : '_blank',
			);
		case 'repeater':
			$rows = array();
			foreach ( (array) $value as $row ) {
				$out = array();
				foreach ( $field['sub_fields'] as $sub ) {
					if ( is_array( $row ) && array_key_exists( $sub['name'], $row ) ) {
						$out[ $sub['key'] ] = majeurs_content_to_acf( $sub, $row[ $sub['name'] ], $missing );
					}
				}
				$rows[] = $out;
			}
			return $rows;
		default:
			return is_scalar( $value ) ? (string) $value : '';
	}
}

/** Media library ID for a wp-content/uploads URL, including a resized copy (-1024x683), a -scaled original or an Elementor crop */
function majeurs_content_attachment_id( $url ) {
	global $wpdb;
	$marker = '/wp-content/uploads/';
	$pos    = strpos( $url, $marker );
	if ( false === $pos ) {
		return 0;
	}
	$file = rawurldecode( substr( $url, $pos + strlen( $marker ) ) );
	// an Elementor crop, elementor/thumbs/<original name>-<hash>.<ext>: the original upload, whatever its extension
	if ( preg_match( '#^elementor/thumbs/(.+)-[a-z0-9]{30,}\.\w+$#', $file, $m ) ) {
		return (int) $wpdb->get_var( $wpdb->prepare(
			"SELECT post_id FROM {$wpdb->postmeta} WHERE meta_key = '_wp_attached_file' AND ( meta_value LIKE %s OR meta_value LIKE %s ) LIMIT 1",
			$wpdb->esc_like( $m[1] ) . '.%',
			'%/' . $wpdb->esc_like( $m[1] ) . '.%'
		) );
	}
	$base   = preg_replace( '/-\d+x\d+(?=\.\w+$)/', '', $file );
	$scaled = preg_replace( '/(\.\w+)$/', '-scaled$1', $base );
	return (int) $wpdb->get_var( $wpdb->prepare(
		"SELECT post_id FROM {$wpdb->postmeta} WHERE meta_key = '_wp_attached_file' AND meta_value IN (%s, %s, %s)
		 ORDER BY FIELD(meta_value, %s, %s, %s) LIMIT 1",
		$file, $base, $scaled, $file, $base, $scaled
	) );
}

